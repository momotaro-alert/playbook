"""Phase5 前半: 環境省・オークション・価格・死亡率だけで計算できる A, F, G, H, K, L。
出力: clean/計算_AFGHKL.csv"""
import numpy as np
import pandas as pd
from phase5_common import *

C = Calc()
td = takedown()
ref, yr = td["ref"], td["yr"]

# ---------- A. 殺処分の減少 vs 引取りの減少 ----------
SRC_A = "clean/引取り処分_全国長期.csv（参考表H16-R06系列）"
for a in ["犬", "猫", "犬猫計"]:
    if a == "犬猫計":
        tk = ref[("犬", "引取り数")] + ref[("猫", "引取り数")]
        kl = ref[("犬", "殺処分数")] + ref[("猫", "殺処分数")]
    else:
        tk, kl = ref[(a, "引取り数")], ref[(a, "殺処分数")]
    k04, k24, t04, t24 = kl[2004], kl[2024], tk[2004], tk[2024]
    C.add("A", a, "殺処分 減少率 2004→2024年度", round((1 - k24 / k04) * 100, 1), "%",
          f"1-{k24:,.0f}/{k04:,.0f}", "参考表の2004年度犬は抑留を勘案した推計値を含む", SRC_A)
    C.add("A", a, "引取り 減少率 2004→2024年度", round((1 - t24 / t04) * 100, 1), "%",
          f"1-{t24:,.0f}/{t04:,.0f}", "同上", SRC_A)
    rate04 = k04 / t04
    C.add("A", a, "殺処分率（殺処分÷引取り）2004年度", round(rate04 * 100, 1), "%", "殺処分÷引取り",
          "負傷動物を含まない", SRC_A)
    C.add("A", a, "殺処分率（殺処分÷引取り）2024年度", round(k24 / t24 * 100, 1), "%", "殺処分÷引取り",
          "負傷動物を含まない", SRC_A)
    # 引取りが減っただけで説明できる殺処分の減少分
    expl = (t04 - t24) * rate04
    C.add("A", a, "殺処分の減少のうち『引取りが減ったこと』で説明できる割合", round(expl / (k04 - k24) * 100, 1), "%",
          "(引取り減少数×2004年度の殺処分率)÷殺処分減少数",
          "2004年度の殺処分率が続いたと仮定（仮定）。残りが譲渡・返還の増加による分", SRC_A)
    # 傾き（年平均変化率） 2004-2012 と 2013-2024
    for s, e in [(2004, 2012), (2012, 2024)]:
        for nm, ser in [("引取り", tk), ("殺処分", kl)]:
            cagr = (ser[e] / ser[s]) ** (1 / (e - s)) - 1
            C.add("A", a, f"{nm} 年平均変化率 {s}→{e}年度", round(cagr * 100, 1), "%/年",
                  f"({ser[e]:,.0f}/{ser[s]:,.0f})^(1/{e-s})-1", "2013年9月の改正法施行（引取り拒否可能）の前後で比較", SRC_A)

# 飼い主からの引取り：2012→2014の2年で何%減ったか（引取り拒否の効果）
for a in ["犬", "猫"]:
    own = yr[(a, "引取り_飼い主から_成熟")] + yr[(a, "引取り_飼い主から_幼齢")]
    unk = yr[(a, "引取り_所有者不明_成熟")] + yr[(a, "引取り_所有者不明_幼齢")]
    C.add("A", a, "飼い主からの引取り 2012→2014年度 減少率", round((1 - own[2014] / own[2012]) * 100, 1), "%",
          f"1-{own[2014]:,.0f}/{own[2012]:,.0f}", "2013年9月から自治体が飼い主・業者からの引取りを拒否できるようになった",
          "clean/引取り処分_全国長期.csv（各年度版系列）")
    C.add("A", a, "所有者不明の引取り 2012→2014年度 減少率", round((1 - unk[2014] / unk[2012]) * 100, 1), "%",
          f"1-{unk[2014]:,.0f}/{unk[2012]:,.0f}", "比較用", "clean/引取り処分_全国長期.csv（各年度版系列）")

# 分類①②③
kc = rd("殺処分分類_全国.csv").drop_duplicates(["年", "動物", "項目"])
for a in ["犬", "猫", "犬猫計"]:
    x = kc[(kc["動物"] == a) & (kc["年"] == 2024)].set_index("項目")["値"]
    tot = x["殺処分数"]
    for k in ["①", "②", "③"]:
        C.add("A", a, f"2024年度 殺処分のうち分類{k}の割合", round(x[f"殺処分数_{k}"] / tot * 100, 1), "%",
              f"{x[f'殺処分数_{k}']:,.0f}/{tot:,.0f}", "①譲渡不適 ②それ以外 ③収容後の死亡", "clean/殺処分分類_全国.csv")
    C.add("A", a, "2024年度『②だけ数える』と殺処分は何頭か", x["殺処分数_②"], "頭",
          "分類②のみ", "東京都・神奈川県と同じ数え方を全国に当てはめた場合（計算）", "clean/殺処分分類_全国.csv")
    for y in [2018, 2024]:
        z = kc[(kc["動物"] == a) & (kc["年"] == y)].set_index("項目")["値"]
        C.add("A", a, f"{y}年度 分類② 頭数", z["殺処分数_②"], "頭", "—", "2018年度は自治体合計（計算）",
              "clean/殺処分分類_全国.csv", 区分="実測" if y == 2024 else "計算")
    z18 = kc[(kc["動物"] == a) & (kc["年"] == 2018)].set_index("項目")["値"]
    C.add("A", a, "分類② 減少率 2018→2024年度", round((1 - x["殺処分数_②"] / z18["殺処分数_②"]) * 100, 1), "%",
          "1-②2024/②2018", "国の目標（2030年度に2018年度比半減）は②の削減を重点にしている", "clean/殺処分分類_全国.csv")
    C.add("A", a, "分類①＋③ 減少率 2018→2024年度",
          round((1 - (x["殺処分数_①"] + x["殺処分数_③"]) / (z18["殺処分数_①"] + z18["殺処分数_③"])) * 100, 1), "%",
          "1-(①+③)2024/(①+③)2018", "", "clean/殺処分分類_全国.csv")

# ---------- G. 繁殖業者数 vs 業界の「32%廃業」「13万頭」 ----------
bz = rd("動物取扱業_登録数_全国.csv").pivot_table(index="基準日", columns="項目", values="値", aggfunc="first")
br = bz["第一種_犬猫等販売業のうち繁殖を行う者"]
for d0, d1 in [("2021-04-01", "2025-04-01"), ("2014-04-01", "2025-04-01")]:
    C.add("G", "犬猫計", f"繁殖を行う者 登録数 変化率 {d0[:4]}→{d1[:4]}（4月1日）",
          round((br[d1] / br[d0] - 1) * 100, 1), "%", f"{br[d1]:,.0f}/{br[d0]:,.0f}-1",
          "数値規制は2021年6月施行、2022・2023年6月に段階引下げ、2024年6月完全施行。登録数は事業所の数で、頭数ではない",
          "clean/動物取扱業_登録数_全国.csv")
sv = rd("繁殖_業界アンケート.csv")
C.add("G", "犬猫計", "業界予測どおりなら2025年の繁殖業者数（犬で32.3%が廃業した場合の目安）",
      round(br["2021-04-01"] * (1 - 0.323)), "事業所", "2021年4月の繁殖を行う者×(1-0.323)",
      "犬猫の区別ができないため犬の廃業検討率32.3%を全体に当てた粗い目安（推測）。アンケートは『廃業も視野』で確定ではない",
      "clean/繁殖_業界アンケート.csv, clean/動物取扱業_登録数_全国.csv", 区分="推測")
C.add("G", "犬猫計", "実際の2025年4月の繁殖を行う者", br["2025-04-01"], "事業所", "—", "", "clean/動物取扱業_登録数_全国.csv", 区分="実測")
C.add("G", "犬猫計", "譲受飼養業（引き取り屋の受け皿）登録数 変化 2021→2025",
      bz["第一種_譲受飼養業"]["2025-04-01"] - bz["第一種_譲受飼養業"]["2021-04-01"], "事業所",
      "2025-04-01 − 2021-04-01", "繁殖引退・余剰の犬猫の有償引取り業。2013年9月に業種新設", "clean/動物取扱業_登録数_全国.csv")
C.add("G", "犬猫計", "第二種（保護団体等）譲渡し 届出数 変化 2021→2025",
      bz["第二種_譲渡し"]["2025-04-01"] - bz["第二種_譲渡し"]["2021-04-01"], "事業所", "—",
      "", "clean/動物取扱業_登録数_全国.csv")

# ---------- H. 立入検査 vs 処分 ----------
en = rd("行政処分_立入検査.csv")
en = en[en["集計単位"].astype(str).str.startswith("全国")]
st = en.pivot_table(index="年", columns="標準項目", values="値", aggfunc="sum")
kok = en[en["項目"].astype(str).str.match(r"告発_第一種")].groupby("年")["値"].sum()
rowsH = []
for y in range(2012, 2025):
    ins = st.loc[y, "立入検査件数（第一種）"]
    adv = st.loc[y, "勧告（第一種）"]; od = st.loc[y, "措置命令（第一種）"]
    can = st.loc[y, "登録取消命令"]; sus = st.loc[y, "業務停止命令"]
    k = kok.get(y, np.nan)
    tot = adv + od + can + sus + (0 if np.isnan(k) else k)
    rowsH.append((y, ins, adv, od, sus, can, k, tot))
    C.add("H", "犬猫計(全業種)", f"{y}年度 立入検査1万件あたりの勧告・命令・停止・取消・告発", round(tot / ins * 10000, 1), "件/1万件",
          f"({adv:.0f}+{od:.0f}+{sus:.0f}+{can:.0f}+告発{0 if np.isnan(k) else k:.0f})/{ins:,.0f}×10000",
          "第一種のみ。指導（口頭・文書）は統計に出ない。東京都等の欠落年あり（log参照）", "clean/行政処分_立入検査.csv")
H = pd.DataFrame(rowsH, columns=["年", "立入検査件数", "勧告", "措置命令", "業務停止", "登録取消", "告発(第一種)", "処分等合計"])
ins_sum = H["立入検査件数"].sum(); act_sum = H["処分等合計"].sum()
C.add("H", "犬猫計(全業種)", "2012〜2024年度 累計：立入検査件数", ins_sum, "件", "合計", "", "clean/行政処分_立入検査.csv")
C.add("H", "犬猫計(全業種)", "2012〜2024年度 累計：勧告・命令・停止・取消・告発", act_sum, "件", "合計", "", "clean/行政処分_立入検査.csv")
C.add("H", "犬猫計(全業種)", "2012〜2024年度 累計：処分等÷立入検査", round(act_sum / ins_sum * 100, 3), "%", "—", "", "clean/行政処分_立入検査.csv")
C.add("H", "犬", "オークション調査：調べたブリーダーの違反率", round(700 / 1400 * 100, 0), "%", "約700÷約1,400事業所",
      "調査先は曜日の偏り（生年月日の不自然さ）がある事業者から自治体が選んだもの。無作為ではない",
      "clean/オークション_環境省調査.csv")

# ---------- K. オークション 自称 vs 実数 ----------
K_SRC = "clean/オークション_自称vs実数.csv"
