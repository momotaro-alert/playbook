"""Phase5 後半: 協会推計・業者報告・狂犬病・マイクロチップを使う B, C, D, E, F, I, J。
出力: clean/計算_BCDEFIJ.csv, clean/計算_D_頭数収支.csv"""
import numpy as np
import pandas as pd
from phase5_common import *

C = Calc()
PF = "clean/新規飼育.csv, clean/入手先構成.csv, clean/入手価格.csv（ペットフード協会）"

# ---------- 共通の入力 ----------
nw = rd("新規飼育.csv")
new = nw[(nw["項目"] == "新規飼育頭数") & nw["推計式"].astype(str).str.startswith("新式")].pivot_table(index="年", columns="動物", values="値") * 1000
pop = rd("飼育頭数_協会推計.csv")
popn = pop[(pop["項目"] == "飼育頭数") & pop["推計式"].astype(str).str.startswith("新式")].pivot_table(
    index="年", columns="動物", values="値") * 1000
popo = pop[(pop["項目"] == "飼育頭数") & pop["推計式"].astype(str).str.startswith("旧式（全世帯")].pivot_table(
    index="年", columns="動物", values="値") * 1000
life = rd("平均寿命.csv")
life = life[life["項目"] == "平均寿命（全体）"].pivot_table(index="年", columns="動物", values="値")
src = rd("入手先構成.csv").pivot_table(index="項目", columns=["動物", "年"], values="値", aggfunc="first")
pr = rd("入手価格.csv").pivot_table(index="項目", columns=["動物", "年"], values="値", aggfunc="first")
dl = rd("業者定期報告_販売死亡.csv")


def share(a, y, keys):
    return sum(src.get((a, y), pd.Series(dtype=float)).get(f"入手先 {k}（1年以内飼育開始者）", np.nan) for k in keys) / 100


DEALER = ["ペットショップで購入", "業者のブリーダーから直接購入"]
dshare = {a: {y: share(a, y, DEALER) for y in (2023, 2024, 2025)} for a in ["犬", "猫"]}
dsh_avg = {a: np.nanmean(list(dshare[a].values())) for a in dshare}
paid = {a: np.nanmean([pr.get((a, y), pd.Series(dtype=float)).get("有償入手率（1年以内飼育開始者）", np.nan) for y in (2023, 2024)]) / 100
        for a in ["犬", "猫"]}
for a in ["犬", "猫"]:
    for y, v in dshare[a].items():
        C.add("B", a, f"{y}年 新規飼育（1年以内）のうち業者経由（ショップ＋業者ブリーダー）の割合", round(v * 100, 1), "%",
              "ペットショップ＋業者のブリーダー（複数回答の単純合計）", "協会調査は複数回答。合計100%にならない", PF)

# ---------- B. 業者の販売（延べ）÷2 vs 家庭の購入 ----------
def dval(y, a, item):
    r = dl[(dl["年"] == y) & (dl["動物"] == a) & (dl["項目"] == item)]["値"].dropna()
    return r.iloc[0] if len(r) else np.nan

Brows = []
for y in [2014, 2015, 2018, 2022]:
    for a in ["犬", "猫"]:
        s = dval(y, a, "販売・引渡し数（延べ）")
        if np.isnan(s):
            C.add("B", a, f"{y}年度 業者の販売・引渡し（延べ）", "取得失敗", "", "—",
                  "全国値が見つからない（logs/phase2.md）", "clean/業者定期報告_販売死亡.csv", 区分="—")
            continue
        n = new[a].get(y, np.nan)
        hh = n * dsh_avg[a]
        hh_spec = n * paid[a] * dsh_avg[a]
        Brows.append(dict(年=y, 動物=a, 業者販売延べ=s, 延べの半分=s / 2, 新規飼育=n, 家庭の業者経由購入=hh, 指示書式=hh_spec))
        C.add("B", a, f"{y}年度 業者販売（延べ）÷2", round(s / 2), "頭", f"{s:,.0f}÷2",
              "延べ数は『繁殖業者→（競り）→店→家庭』で同じ子が2回数えられると仮定（÷2）。繁殖引退した親の譲渡も含む", "clean/業者定期報告_販売死亡.csv（二次：朝日新聞集計）")
        C.add("B", a, f"{y}年 家庭の業者経由購入（新規飼育×業者経由率）", round(hh), "頭",
              f"{n:,.0f}×{dsh_avg[a]:.3f}", "業者経由率は2023-25年の平均を過去年に当てはめた（仮定）。協会調査は暦年・調査時点から1年以内", PF)
        C.add("B", a, f"{y}年 家庭の購入（指示書の式：新規飼育×有償入手率×業者経由率）", round(hh_spec), "頭",
              f"{n:,.0f}×{paid[a]:.3f}×{dsh_avg[a]:.3f}", "業者経由はそもそも有償なので有償率を掛けると二重に割り引く。参考値", PF)
        C.add("B", a, f"{y}年度 差分（業者販売÷2 − 家庭の業者経由購入）", round(s / 2 - hh), "頭", "上の2つの差",
              "年度（業者）と暦年（協会）が半年ずれる。プラスなら『業者は売ったが家庭に届いていない（または調査に映らない）』頭数", "計算")
        C.add("B", a, f"{y}年度 延べ数を何で割ると家庭の購入と一致するか", round(s / hh, 2), "（割る数）", "延べ÷家庭の業者経由購入",
              "1なら直販のみ、2なら全て業者を2回経由。現実は1〜2の間のはず", "計算")
pd.DataFrame(Brows).to_csv(f"{CLEAN}/計算_B_業者販売と家庭購入.csv", index=False, encoding="utf-8-sig")

# ---------- C. マイクロチップ純増 vs 家庭の購入 ----------
mc = rd("マイクロチップ.csv")
mc = mc[(mc["地域"] == "全国") & (mc["項目"] == "登録頭数_年度純増（累積差）")].drop_duplicates(["年", "動物"]).pivot_table(
    index="年", columns="動物", values="値")
Crows = []
for y in [2023, 2024]:
    for a in ["犬", "猫"]:
        net = mc.loc[y, a]
        n = new[a][y]
        hh = n * dshare[a][y]
        Crows.append(dict(年=y, 動物=a, MC純増=net, 新規飼育=n, 業者経由購入=hh))
        C.add("C", a, f"{y}年度 マイクロチップ登録 純増", net, "頭", "年度末累積の差", "死亡等の届出で消えた分を差し引いた純増",
              "clean/マイクロチップ.csv", 区分="実測")
        C.add("C", a, f"{y} マイクロチップ純増 − 家庭の業者経由購入", round(net - hh), "頭",
              f"{net:,.0f} − {n:,.0f}×{dshare[a][y]:.3f}",
              "義務は販売業者のみ。繁殖用の親・売れ残り・家庭に届く前に死んだ子も登録されうる。年度と暦年のずれあり", "計算")
        C.add("C", a, f"{y} マイクロチップ純増 ÷ 新規飼育（全入手経路）", round(net / n * 100, 1), "%",
              f"{net:,.0f}÷{n:,.0f}", "業者経由でない子（譲渡・拾い）は義務ではないのに、純増が新規飼育全体に近い", "計算")
pd.DataFrame(Crows).to_csv(f"{CLEAN}/計算_C_チップと購入.csv", index=False, encoding="utf-8-sig")

# ---------- D. 頭数の収支 ----------
Drows = []
for a in ["犬", "猫"]:
    for y in range(2014, 2026):
        p, p0 = popn[a].get(y), popn[a].get(y - 1)
        L = life[a].get(y, np.nan)
        dth = p / L
        Drows.append(dict(年=y, 動物=a, 飼育頭数=p, 前年差=p - p0, 新規飼育=new[a][y], 推計死亡=dth,
                          新規と死亡の差=new[a][y] - dth, 合わない頭数=(p - p0) - (new[a][y] - dth)))
D = pd.DataFrame(Drows)
D.to_csv(f"{CLEAN}/計算_D_頭数収支.csv", index=False, encoding="utf-8-sig")
for a in ["犬", "猫"]:
    x = D[(D["動物"] == a) & (D["年"] >= 2021)]
    C.add("D", a, "2021-2025年 平均：新規飼育", round(x["新規飼育"].mean()), "頭/年", "協会値の平均", "", PF, 区分="計算")
    C.add("D", a, "2021-2025年 平均：推計死亡（飼育頭数÷平均寿命）", round(x["推計死亡"].mean()), "頭/年", "飼育頭数÷平均寿命",
          "平均寿命は『死んだ子の平均年齢』で、頭数が一定なら年間死亡≒頭数÷寿命（定常の仮定）", PF)
    C.add("D", a, "2021-2025年 平均：実際の飼育頭数の前年差", round(x["前年差"].mean()), "頭/年", "協会値の差", "", PF)
    C.add("D", a, "2021-2025年 平均：収支の合わない頭数（前年差 −（新規−死亡））", round(x["合わない頭数"].mean()), "頭/年",
          "前年差 −（新規飼育 − 推計死亡）", "0に近いほど3つの数字が同時に成り立つ", "計算")

# ---------- E. 狂犬病登録率 ----------
rb = rd("狂犬病_登録注射.csv")
reg = rb[rb["項目"] == "登録頭数"].drop_duplicates("年").set_index("年")["値"]
for y, base, lab in [(2008, popo, "旧式"), (2010, popo, "旧式"), (2013, popo, "旧式"), (2013, popn, "新式（遡及）"),
                     (2020, popo, "旧式"), (2020, popn, "新式（遡及）"), (2025, popn, "新式")]:
    v = reg[y] / base["犬"][y]
    C.add("E", "犬", f"{y}年 登録率（狂犬病登録÷協会推計・{lab}）", round(v * 100, 1), "%",
          f"{reg[y]:,.0f}÷{base['犬'][y]:,.0f}", "登録は死亡届が出ないと消えないため実際より多めになりうる。登録は年度、協会は暦年10月頃",
          "clean/狂犬病_登録注射.csv, clean/飼育頭数_協会推計.csv")
C.add("E", "猫", "猫の登録率", "検証不能（猫には登録制度がない）", "", "—", "", "—", 区分="—")
nreg = rb[rb["項目"] == "新規登録申請数"].drop_duplicates("年").set_index("年")["値"]
for y in [2023, 2024, 2025]:
    if y in nreg:
        C.add("E", "犬", f"{y}年度 狂犬病の新規登録 ÷ 協会の新規飼育", round(nreg[y] / new["犬"][y] * 100, 1), "%",
              f"{nreg[y]:,.0f}÷{new['犬'][y]:,.0f}", "新規登録には業者が持つ繁殖犬・売れ残りの登録も含まれうる（推測）", "clean/狂犬病_登録注射.csv")

# ---------- F. 死亡率 ----------
SF = "clean/業者定期報告_販売死亡.csv, clean/死亡率_国内外比較.csv"
C.add("F", "犬", "国（2014年度）の死亡率", 2.9, "%", "死亡÷（販売・引渡し延べ等）", "死産・親を含まない。分母が延べ", SF, 区分="実測")
C.add("F", "犬", "分母を『実際の子の数』（延べ÷2）にした死亡率", round(18517 / (617009 / 2 + 18517) * 100, 1), "%",
      "18,517÷(617,009÷2＋18,517)", "延べ÷2は仮定", SF)
C.add("F", "犬", "フランス繁殖場：生きて生まれた子のうち生後2か月までに死ぬ割合", round((13.4 - 7.4) / (100 - 7.4) * 100, 1), "%",
      "(13.4−7.4)÷(100−7.4)", "死産を除いて日本の定期報告と定義をそろえた", SF)
C.add("F", "犬", "フランス並みの死亡率なら2014年度の死亡数は", round((617009 / 2) / (1 - 0.0648) * 0.0648), "頭",
      "(延べ÷2)÷(1−0.0648)×0.0648", "家庭に届いた子＝延べ÷2と仮定（推測）", SF, 区分="推測")
C.add("F", "犬", "実際の2014年度の死亡数（業者報告）", 18517, "頭", "—", "", SF, 区分="二次")
C.add("F", "犬", "死産を含めると（フランス並み7.4%）2014年度に見えない死産は", round((617009 / 2 + 18517) / (1 - 0.074) * 0.074), "頭",
      "(延べ÷2＋死亡)÷(1−0.074)×0.074", "日本の報告は死産を含まない。フランス並みと仮定（推測）", SF, 区分="推測")
C.add("F", "犬", "クーリク社 繁殖施設 2023年1-8月 死亡率（死産含む・会社公表）", 18.4, "%", "—", "", SF, 区分="実測")
C.add("F", "犬", "クーリク社 店舗段階 入舎後死亡率 2023年", 1.03, "%", "—", "『死亡率1%前後』はこの段階の数字", SF, 区分="実測")

# ---------- I. 猫：業者販売の伸び vs ショップ購入の伸び ----------
s14, s22 = 133554, 252417
C.add("I", "猫", "業者の販売・引渡し（延べ）2014→2022年度 伸び率", round((s22 / s14 - 1) * 100, 1), "%", "252,417÷133,554−1",
      "2022年度は『2014年度比89%増』という報道から逆算（計算）", "clean/業者定期報告_販売死亡.csv")
C.add("I", "猫", "新規飼育頭数 2014→2022年 伸び率", round((new["猫"][2022] / new["猫"][2014] - 1) * 100, 1), "%",
      f"{new['猫'][2022]:,.0f}÷{new['猫'][2014]:,.0f}−1", "", PF)
C.add("I", "猫", "業者経由率が一定なら、家庭の業者経由購入の伸び", round((new["猫"][2022] / new["猫"][2014] - 1) * 100, 1), "%",
      "新規飼育の伸びと同じ", "2014年の入手先構成は公開されていない（仮定）", PF)
exp22 = s14 / 2 * new["猫"][2022] / new["猫"][2014]
C.add("I", "猫", "需要の伸びを超えて増えた業者販売（2022年度、延べ÷2ベース）", round(s22 / 2 - exp22), "頭/年",
      "252,417÷2 − 133,554÷2×(新規2022÷新規2014)", "業者経由率が変わっていないと仮定（推測）", "計算", 区分="推測")
C.add("I", "猫", "業者経由率がいくら上がれば説明できるか（2014→2022）", round((s22 / s14) / (new["猫"][2022] / new["猫"][2014]), 2), "倍",
      "販売の伸び÷新規飼育の伸び", "2014年の業者経由率が2022年の何分の1だったら合うか", "計算")

# ---------- J. 猫：野良拾い ----------
for y in (2023, 2024, 2025):
    st = share("猫", y, ["野良犬・猫を拾った"]); fr = share("猫", y, ["友人/知人/親族からの無償譲渡"])
    dl_ = dshare["猫"][y]
    n = new["猫"][y]
    C.add("J", "猫", f"{y}年 新規飼育のうち野良拾い", round(n * st), "頭", f"{n:,.0f}×{st:.3f}", "1年以内飼育開始者の構成比", PF)
    C.add("J", "猫", f"{y}年 新規飼育のうち知人からの無償譲渡", round(n * fr), "頭", f"{n:,.0f}×{fr:.3f}", "多くは飼い猫・外猫の子と推測", PF)
    C.add("J", "猫", f"{y}年 新規飼育のうち業者経由", round(n * dl_), "頭", f"{n:,.0f}×{dl_:.3f}", "", PF)
    dth = D[(D["動物"] == "猫") & (D["年"] == y)]["推計死亡"].iloc[0]
    C.add("J", "猫", f"{y}年 野良拾いを除いた新規 − 推計死亡", round(n * (1 - st) - dth), "頭", "新規×(1−野良拾い率)−推計死亡",
          "マイナス＝飼い猫の数を保てない", "計算")
C.add("J", "犬", "犬の新規飼育のうち野良拾い（2025年）", round(new["犬"][2025] * share("犬", 2025, ["野良犬・猫を拾った"])), "頭",
      "—", "犬はほぼ0%。犬の供給はほぼ業者だけ", PF)

C.save("計算_BCDEFIJ.csv")
print(pd.DataFrame(C.rows)[["計算記号", "動物", "項目", "値", "単位"]].to_string())
