def clean_tokens(nums):
    out, notes = [], []
    for t in nums:
        t2 = t.translate(Z2H)
        if t2 in ('※', '*', '＊'):
            notes.append('※')
            continue
        if re.fullmatch(r'[（(]?※[0-9０-９]*[）)]?', t2):
            out.append('-')
            notes.append('※欄')
            continue
        m = re.fullmatch(r'([\d,]+)\s*[（(]?※[0-9０-９]*[）)]?', t2)
        if m:
            out.append(m.group(1))
            notes.append('※')
            continue
        out.append(t)
    return out, notes


