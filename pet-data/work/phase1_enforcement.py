        if not (name == '合計' or pref_of(name)):
            continue
        # 東京都等の注記付きトークンを処理
        toks = line.split()
        i = 0
        while i < len(toks) and not (re.match(r'^[\d,]+|^[（(]?※', toks[i].translate(Z2H)) or toks[i] in MISSING):
            i += 1
        rest = [('-' if t in ('計予定', '集計') else t) for t in toks[i:]]
        if (fy, name) in FIX:
            rest = FIX[(fy, name)].split()
        nums, notes = clean_tokens(rest)
        nums = [t for t in nums if is_num(t)]
        note = '原表注記あり（東京都等は延べ立入件数のみ等）' if notes else ''
