# ---- 計算: 死亡率
def val(y, a, item):
    for r in rows:
        if r['年'] == y and r['動物'] == a and r['項目'] == item and r['値'] != '':
            return r['値'], r['出典URL']
    return None, None


for y in (2014, 2015):
    for a in ('犬', '猫'):
        s, url = val(y, a, '販売・引渡し数（延べ）')
        d, _ = val(y, a, '死亡数')
        if s and d:
            add(y, a, '死亡率（死亡÷(販売・引渡し+死亡)）', round(d / (s + d) * 100, 2), '%', '計算', '計算（上記二次値から）', url,
                '環境省の定義（死亡/(販売又は引渡し+死亡)）で計算。延べ数ベースのため個体ベースより低く出る' + ('。販売数が千匹単位の概数' if y == 2015 else ''), 99)
            add(y, a, '死亡率（死亡÷販売・引渡し）', round(d / s * 100, 2), '%', '計算', '計算（上記二次値から）', url,
                '朝日・議会録の「流通量の3%」はこの定義に近い', 99)
s1, _ = val(2014, '犬', '販売・引渡し数（延べ）'); s2, _ = val(2014, '猫', '販売・引渡し数（延べ）')
