_cache = {}


def page_text(fn):
    if fn not in _cache:
        p = os.path.join(RAW, fn)
        if fn.endswith('.pdf'):
            _cache[fn] = subprocess.run(['pdftotext', '-layout', p, '-'], capture_output=True, text=True).stdout
        else:
            s = BeautifulSoup(open(p, 'rb').read(), 'html.parser')
            _cache[fn] = s.get_text(' ', strip=True)
        _cache[fn] = re.sub(r'\s+', '', _cache[fn])
    return _cache[fn]


def check(fn, needle):
    if re.sub(r'\s+', '', needle) not in page_text(fn):
        problems.append(f'根拠文字列が見つからない: {fn}: {needle}')


