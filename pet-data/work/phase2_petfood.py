def text(path, pages=None):
    with pdfplumber.open(path) as pdf:
        ps = pdf.pages if pages is None else [pdf.pages[i] for i in pages]
        return '\n'.join((p.extract_text() or '') for p in ps)


def nums(s):
    return [float(x.replace(',', '')) for x in re.findall(r'[\d,]+\.?\d*', s)]


